/**
 * SECTION:element-overlaycompositor
 *
 * Blends upstream `GstVideoOverlayCompositionMeta` into video frames
 * if downstream does not support the metadata.
 *
 * |[
 * gst-launch-1.0 videotestsrc num-buffers=1 ! timeoverlay ! overlaycompositor ! x264enc ! fakesink
 * ]| This blends the overlay metadata generated by `timeoverlay` into
 * video frames and encodes them into an H.264 stream.
 *
 * Since: plugins-rs-0.16.0
 */
use gst::glib;
use gst::prelude::*;

mod imp;

glib::wrapper! {
    pub struct OverlayCompositor(ObjectSubclass<imp::OverlayCompositor>) @extends gst::Element, gst::Object;
}

pub fn register(plugin: &gst::Plugin) -> Result<(), glib::BoolError> {
    gst::Element::register(
        Some(plugin),
        "overlaycompositor",
        gst::Rank::NONE,
        OverlayCompositor::static_type(),
    )
}
