use gst::glib;
use gst::prelude::*;

pub mod imp;

glib::wrapper! {
    pub struct RtpH263PDepay(ObjectSubclass<imp::RtpH263PDepay>)
        @extends crate::basedepay::RtpBaseDepay2, gst::Element, gst::Object;
}

pub fn register(plugin: &gst::Plugin) -> Result<(), glib::BoolError> {
    gst::Element::register(
        Some(plugin),
        "rtph263pdepay2",
        gst::Rank::PRIMARY,
        RtpH263PDepay::static_type(),
    )
}
